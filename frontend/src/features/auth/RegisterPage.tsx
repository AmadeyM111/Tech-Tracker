// 019/R8-T16: self-registration request screen /register (FR-2, FR-3, FR-4, AC-1, AC-2).
import { GTrackLogo } from "../../shared/ui/GTrackLogo";
import { useQuery } from "@tanstack/react-query";
import { useEffect, useRef, useState, type FormEvent, type RefObject } from "react";
import { Link } from "react-router-dom";

import { ApiError } from "../../shared/api/client";
import { PASSWORD_MIN_LENGTH, errorMessage, t, type MessageKey } from "../../shared/i18n";
import { ErrorAlert, useAlertState } from "../../shared/ui/ErrorAlert";
import { TextField } from "../../shared/ui/TextField";
import { passwordResetStatus, requestRegistration, type RegistrationRequest } from "./api";
import "./auth-screens.css";

type FieldKey = "email" | "firstName" | "lastName" | "password";

// Text under an empty field (design register-err-empty, 2026-11-10).
const EMPTY_TEXT: Record<FieldKey, MessageKey> = {
  email: "auth.register_email_required",
  firstName: "auth.register_first_name_required",
  lastName: "auth.register_last_name_required",
  password: "auth.register_password_required",
};

// The field the error refers to; it is marked invalid, the text stays above the submit button (design 2026-11-08).
// v0.5 (2026-11-09): the login is generated by the server, so login_taken has no field here.
function badFieldFor(code: string): "email" | null {
  if (code === "email_invalid") return "email";
  return null;
}

export function RegisterPage() {
  const alert = useAlertState();
  const emailRef = useRef<HTMLInputElement>(null);
  const firstNameRef = useRef<HTMLInputElement>(null);
  const lastNameRef = useRef<HTMLInputElement>(null);
  const passwordRef = useRef<HTMLInputElement>(null);
  const busy = useRef(false);
  const [email, setEmail] = useState("");
  const [firstName, setFirstName] = useState("");
  const [lastName, setLastName] = useState("");
  const [password, setPassword] = useState("");
  const [shown, setShown] = useState(false);
  const [pending, setPending] = useState(false);
  const [sent, setSent] = useState(false);
  // feature_disabled on submit (FR-1): the form is hidden as if registration were off (plan §10, p. 2).
  const [off, setOff] = useState(false);
  const [badField, setBadField] = useState<"email" | null>(null);
  // Fields that were empty on the last submit; each shows its text under it (cleared on the next submit).
  const [emptyKeys, setEmptyKeys] = useState<FieldKey[]>([]);

  // The same query and key as on /login (RG-13): the status is shared, no extra request is made.
  const status = useQuery({
    queryKey: ["auth", "password-reset-status"],
    queryFn: () => passwordResetStatus(),
    retry: false,
    refetchOnWindowFocus: false,
  });
  const registrationOff = off || status.data?.enabled === false;

  useEffect(() => {
    emailRef.current?.focus();
  }, []);

  const emptyError = (key: FieldKey): string | null => (emptyKeys.includes(key) ? t(EMPTY_TEXT[key]) : null);

  async function onSubmit(event: FormEvent<HTMLFormElement>): Promise<void> {
    event.preventDefault();
    if (busy.current) return;
    // Spaces at the ends count as empty. The first empty field takes focus; the general alert above the button does not.
    const fields: { key: FieldKey; value: string; ref: RefObject<HTMLInputElement> }[] = [
      { key: "email", value: email, ref: emailRef },
      { key: "firstName", value: firstName, ref: firstNameRef },
      { key: "lastName", value: lastName, ref: lastNameRef },
      { key: "password", value: password, ref: passwordRef },
    ];
    const missing = fields.filter((f) => f.value.trim() === "");
    setEmptyKeys(missing.map((f) => f.key));
    if (missing.length > 0) {
      alert.show(errorMessage("validation_error"));
      missing[0]?.ref.current?.focus();
      return;
    }
    const body: RegistrationRequest = {
      email: email.trim(),
      first_name: firstName.trim(),
      last_name: lastName.trim(),
      password,
    };
    busy.current = true;
    setPending(true);
    alert.clear();
    setBadField(null);
    try {
      await requestRegistration(body);
      setSent(true);
    } catch (e) {
      const code = e instanceof ApiError ? e.code : "unknown";
      if (code === "feature_disabled") {
        setOff(true);
      } else {
        setBadField(badFieldFor(code));
        alert.show(errorMessage(code));
      }
    } finally {
      busy.current = false;
      setPending(false);
    }
  }

  return (
    <section className="ui-form login-card">
      <div className="ui-brand">
        <GTrackLogo />
        <h1>{t("auth.register_title")}</h1>
      </div>
      {registrationOff ? (
        <p>{t("auth.register_disabled")}</p>
      ) : sent ? (
        <p role="status" className="reg-status">
          {t("auth.register_sent")}
        </p>
      ) : (
        <form className="reg-form" onSubmit={(e) => void onSubmit(e)} noValidate>
          <TextField
            label={t("auth.register_email_label")}
            value={email}
            onChange={setEmail}
            autoComplete="email"
            inputRef={emailRef}
            invalid={badField === "email"}
            error={emptyError("email")}
            disabled={pending}
          />
          <TextField
            label={t("auth.register_first_name_label")}
            value={firstName}
            onChange={setFirstName}
            autoComplete="given-name"
            inputRef={firstNameRef}
            error={emptyError("firstName")}
            disabled={pending}
          />
          <TextField
            label={t("auth.register_last_name_label")}
            value={lastName}
            onChange={setLastName}
            autoComplete="family-name"
            inputRef={lastNameRef}
            error={emptyError("lastName")}
            disabled={pending}
          />
          <TextField
            label={t("auth.register_password_label")}
            type="password"
            value={password}
            onChange={setPassword}
            autoComplete="new-password"
            inputRef={passwordRef}
            hint={t("auth.password_min_length_hint", { min: PASSWORD_MIN_LENGTH })}
            error={emptyError("password")}
            disabled={pending}
            reveal={{
              label: shown ? t("auth.hide_password") : t("auth.show_password"),
              shown,
              onToggle: () => setShown((v) => !v),
            }}
          />
          {/* Focus stays on the first empty field: the alert takes focus only for server errors. */}
          <ErrorAlert message={alert.message} seq={alert.seq} focus={emptyKeys.length === 0} />
          <button type="submit" className="login-submit" disabled={pending}>
            {t("auth.register_submit")}
          </button>
        </form>
      )}
      <div className="login-links">
        <Link to="/login">{t("auth.register_back_to_login")}</Link>
      </div>
    </section>
  );
}
