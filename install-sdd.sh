2. Заполни шаблон и сохрани `specs/<NNN-slug>/spec.md`. Пиши только этот файл.

## Правила качества
- **ЧТО, а не КАК.** Никаких имён классов, файлов, библиотек и алгоритмов, если это не внешнее
  требование пользователя (например, «должно работать с существующим API X»).
- **Каждый критерий приёмки проверяем автоматически или однозначно вручную.** Формат
  Given/When/Then. Плохо: «модель работает быстро». Хорошо: «при батче 256 на A100
  инференс занимает ≤ 50 мс p95».
- **Для ML-требований всегда указывай:** метрику, порог, на каком сплите/датасете, как
  фиксируется seed, допуск (±) и на чём проверяется в CI (обычно — маленький фикстурный
  набор, а полный прогон — вне цикла).
- **Граничные случаи и ошибки** — отдельные критерии: пустой вход, NaN, неверная размерность,
  отсутствующий файл, нехватка памяти GPU и т.п., если применимо.
- **Вне рамок (Out of scope)** — обязательно заполнить. Это защита от расползания задачи.
- **Не выдумывай ответы на неясности.** Каждую неясность помечай в тексте как
  `[NEEDS CLARIFICATION: вопрос]` и выноси в раздел «Открытые вопросы» с вариантами ответа
  и твоим рекомендованным вариантом. Ты не можешь спросить пользователя сам — это сделает
  оркестратор.
- Нумеруй требования `FR-1…`, `NFR-1…`, критерии `AC-1…` — на них будут ссылаться
  задачи, тесты и ревью. После утверждения spec номера не перенумеровывай.

## Формат ответа оркестратору (коротко, не пересказывай spec целиком)
- Путь к файлу.
- Сводка в 3–5 строк: суть фичи, число FR/NFR/AC.
