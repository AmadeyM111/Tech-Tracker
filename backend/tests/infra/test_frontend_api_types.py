"""T22: сгенерированные TS-типы (plan §4.14, D-33, FR-44).

``schema.d.ts`` не правится вручную: совпадает с выводом ``openapi-typescript`` из
``docs/api/openapi.json``; ``scripts/gen-api.sh`` идемпотентен и не меняет ``openapi.json``.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

import pytest

pytestmark = pytest.mark.infra_static

REPO = Path(__file__).resolve().parents[3]
FE = REPO / "frontend"
SCHEMA = FE / "src" / "shared" / "api" / "schema.d.ts"
OPENAPI = REPO / "docs" / "api" / "openapi.json"
GEN = REPO / "scripts" / "gen-api.sh"
OTS = FE / "node_modules" / ".bin" / "openapi-typescript"


def _spec() -> dict[str, Any]:
    data = json.loads(OPENAPI.read_text(encoding="utf-8"))
    assert isinstance(data, dict)
    return data


def _schema_text() -> str:
    assert SCHEMA.is_file(), "нет frontend/src/shared/api/schema.d.ts (npm run gen:api)"
    return SCHEMA.read_text(encoding="utf-8")


def _need_generator() -> None:
    if not OTS.exists() or shutil.which("node") is None:
        pytest.skip("нет node или frontend/node_modules (npm ci): сравнение пропущено")


def test_t22_schema_exists_and_marked_generated() -> None:
    text = _schema_text()
    assert re.search(r"auto-generated|generated by openapi-typescript", text, re.I)
    assert "export interface paths" in text
    assert '"/api/v1/auth/login"' in text
    assert "ErrorResponse" in text
    assert "ErrorDetail" in text


def test_t22_schema_contains_every_path_method_and_operation_id() -> None:
    text = _schema_text()
    spec = _spec()
    assert spec["paths"]
    for path, item in spec["paths"].items():
        assert f'"{path}"' in text, f"нет пути {path}"
        for method, op in item.items():
            if method not in {"get", "put", "post", "delete", "patch"}:
                continue
            op_id = op["operationId"]
            assert re.search(rf"(?m)^    {re.escape(op_id)}: \{{", text), (
                f"нет operationId {op_id} ({method.upper()} {path})"
            )


def test_t22_schema_contains_every_component_schema() -> None:
    text = _schema_text()
    for name in _spec()["components"]["schemas"]:
        assert re.search(rf"(?m)^        {re.escape(name)}: ", text), f"нет схемы {name}"


def test_t22_schema_matches_fresh_generation(tmp_path: Path) -> None:
    """schema.d.ts не правится вручную: совпадает с выводом openapi-typescript."""
    _need_generator()
    out = tmp_path / "schema.d.ts"
    res = subprocess.run(
        [str(OTS), str(OPENAPI), "-o", str(out)],
        cwd=FE,
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )
    assert res.returncode == 0, res.stderr
    assert out.read_text(encoding="utf-8") == _schema_text()


def test_t22_gen_api_script_has_frontend_part() -> None:
    text = GEN.read_text(encoding="utf-8")
    assert "set -euo pipefail" in text
    assert "gostracker openapi --out docs/api/openapi.json" in text
    assert re.search(r"npm\s+(--prefix\s+frontend\s+run\s+gen:api|run\s+gen:api)", text)
    assert "|| true" not in text
    # порядок: сначала openapi.json, потом типы
    assert text.index("gostracker openapi") < text.index("gen:api")


def test_t22_gen_api_is_idempotent_and_leaves_openapi_unchanged() -> None:
    """Эквивалент ``git diff --exit-code docs/api/openapi.json schema.d.ts`` после gen-api."""
    _need_generator()
    _schema_text()  # schema.d.ts должен быть закоммичен до запуска генерации
    venv_bin = Path(sys.executable).parent
    if not (venv_bin / "gostracker").exists():
        pytest.skip("gostracker не установлен в окружении теста")
    env = {**os.environ, "PATH": f"{venv_bin}{os.pathsep}{os.environ['PATH']}"}
    before = {p: p.read_bytes() for p in (OPENAPI, SCHEMA)}
    try:
        for _ in range(2):
            res = subprocess.run(
                ["bash", str(GEN)],
                cwd=REPO,
                env=env,
                capture_output=True,
                text=True,
                timeout=240,
                check=False,
            )
            assert res.returncode == 0, res.stderr
            for path, content in before.items():
                assert path.read_bytes() == content, f"{path.name} изменился после gen-api.sh"
    finally:
        for path, content in before.items():
            path.write_bytes(content)
